import './test-env.mjs';
import assert from 'node:assert/strict';
import {mkdtempSync} from 'node:fs';
import {tmpdir} from 'node:os';
process.env.VERA_DB=mkdtempSync(tmpdir()+'/vera-diary-')+'/db';
const {journal}=await import('../journal.mjs');
const record={id:'sesion_1',kind:'Entrenamiento',date:'2026-11-15',kg:40};
const save=(rev,record)=>journal('uno',{updates:[{id:'sesion_1',rev,record}]});
assert.equal((await save(0,record)).accepted[0].rev,1);
assert.equal((await save(0,record)).accepted[0].rev,1);
assert.equal((await journal('otro',{})).records.length,0);
assert.equal((await save(1,{...record,kg:42})).accepted[0].rev,2);
assert.equal((await save(1,{...record,kg:43})).conflicts[0].record.kg,42);
assert.equal((await save(2,null)).records[0].record,null);
await assert.rejects(save(3,{...record,source:'health'}));
console.log('PASS · diario privado, reintentos, conflictos y borrado.');
const sets=Array.from({length:26},(_,i)=>({id:'set_fixture_'+i,kind:'Entrenamiento',date:'2026-11-23',exercise:i%2?'Press inclinado':'Aperturas',enteredKg:20,kg:40,loadMode:'side',loadSchema:2,reps:[10],rir:3}));
const batch=sets.map(record=>({id:record.id,rev:0,record}));
const first=await journal('training_fixture',{updates:batch});
assert.equal(first.accepted.length,26);
const revised={...sets[12],reps:[12],rir:2,enteredKg:22.5,kg:45};
await journal('training_fixture',{updates:[{id:revised.id,rev:1,record:revised}]});
const restored=(await journal('training_fixture',{})).records;
assert.equal(restored.length,26);
assert.deepEqual(restored.find(row=>row.id===revised.id).record,revised);
console.log('PASS · 26 series y recuperación de carga, esfuerzo y repeticiones corregidas.');
