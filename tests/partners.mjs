import assert from 'node:assert/strict';
import {mkdtempSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
process.env.TURSO_DATABASE_URL='';
process.env.VERA_DB=join(mkdtempSync(join(tmpdir(),'vera-pair-')),'test.sqlite');
const {partnerAction}=await import('../partners.mjs');
const {nickname}=await import('../accounts.mjs');
const call=(action,uid,d={})=>partnerAction('/partners/'+action,uid,d);
await nickname('a','@Lima');
await nickname('b','Bosque');
await assert.rejects(()=>nickname('c','lima'));
const {room:r}=await call('invite','a',{nick:'@bosque',title:'Tren superior',plan:['Press','Remo'],target:1,mode:'challenge'});
assert.equal((await call('list','b')).rooms[0].id,r.id);
await assert.rejects(()=>call('room','c',{id:r.id}),e=>e.status===404);
await assert.rejects(()=>call('respond','a',{id:r.id,accept:true}),e=>e.status===403);
assert.equal((await call('respond','b',{id:r.id,accept:true})).room.state,'active');
const set={id:r.id,event:'same-event',exercise:0};
await Promise.all([call('set','a',set),call('set','a',set)]);
assert.equal((await call('room','b',{id:r.id})).room.counts[0].n,1);
await assert.rejects(()=>call('set','a',{...set,event:'another-event'}),e=>e.status===409);
await call('set','b',set);
await call('finish','b',{id:r.id});
assert.equal((await call('finish','a',{id:r.id})).room.state,'finished');
assert.equal((await call('room','a',{id:r.id})).room.counts.length,2);
console.log('PASS · nick único, invitación privada, tercero excluido, reto, reintento idempotente, límite de series y cierre.');
